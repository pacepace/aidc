#!/usr/bin/env bash
# shellcheck shell=bash
# The globals set here are read by gitctl and the hook (SC2034).
# shellcheck disable=SC2034
# The git container's hard rules (docs/design-12-kubernetes.md, "Git", K8S-24), shared by
# gitctl (the only way to the GitHub login) and Claude Code's PreToolUse hook.
#
# Every check returns 0 to allow or 1 to refuse, with the one-line reason in GITCTL_REASON.
# No function here calls a helper from another file: a missing one inside `check || die`
# would be swallowed and the refusal lost.

# Names that mark AI authorship, matched case-insensitively.
GITCTL_AI='claude|anthropic|openai|chatgpt|gpt-?[0-9]|copilot|gemini|codex|cursor|codeium|windsurf|tabnine|aider|devin|codewhisperer|cody|deepseek|mistral|llama|grok|qwen|\bai\b|\[bot\]'

gitctl_refuse() { GITCTL_REASON="$1"; return 1; }

# gitctl_attribution TEXT: 0, with the offending line in GITCTL_HIT, when TEXT carries AI
# attribution anywhere: a Co-Authored-By or Signed-off-by naming an AI, a "Generated with"
# (created, written, made...) followed by one, the robot emoji, or a Claude Code link. Anywhere
# on a line, not only at its start: `--body="Thanks. Co-Authored-By: Claude"` is still a
# trailer once GitHub renders it. This is the check for what a push or request SAYS (commit
# messages, PR titles and bodies, comments): there, a line that names Claude without one of
# those shapes passes ("Fix the Claude Code transcript reader"), but a sentence that quotes a
# trailer or a Claude Code link is refused too. The lines a pushed commit adds to FILES have
# their own, narrower check (gitctl_file_attribution_stream).
gitctl_attribution() {
    gitctl_attribution_stream < <(printf '%s\n' "$1")
}

# gitctl_attribution_stream: the same check on stdin, read once, as a stream: the lines a push
# adds can be far larger than a shell variable should hold. 0, with the first offending line in
# GITCTL_HIT, when one carries attribution. Called with a redirect, not in a pipeline, so
# GITCTL_HIT is set in the caller's shell.
gitctl_attribution_stream() {
    GITCTL_HIT=$(LC_ALL=C grep -m1 -iE \
        -e "$(printf '\360\237\244\226')" \
        -e "co[- ]?authored[- ]?by[[:space:]]*:?.*(${GITCTL_AI})" \
        -e "signed[- ]?off[- ]?by[[:space:]]*:.*(${GITCTL_AI})" \
        -e "(generated|created|written|authored|made|produced)[[:space:]]+(with|by|using|via|in)[[:space:]]+[^[:alnum:]]*(${GITCTL_AI})" \
        -e 'claude\.(com|ai)/(claude-)?code') && return 0
    GITCTL_HIT=""
    return 1
}

# Words that name an AI tool in a trailer a FILE carries: GITCTL_AI_ID's whole-word list without
# the words that are also people's first names (devin; cody and aider are not in it), because an
# AUTHORS or CONTRIBUTING line may credit a person. A trailer whose email is at an AI vendor's
# domain names an AI tool whatever its name says (Cody <...@sourcegraph.com>).
GITCTL_AI_FILE_ID='claude|anthropic|openai|chatgpt|gpt[0-9]*|copilot|gemini|codex|cursor|codeium|windsurf|tabnine|codewhisperer|deepseek|bot'
GITCTL_AI_VENDOR_MAIL='anthropic\.com|openai\.com|cognition\.ai|cognition-labs\.com|sourcegraph\.com|aider\.chat|cursor\.(sh|com)|anysphere\.co|codeium\.com|windsurf\.com|tabnine\.com|deepseek\.com'

# gitctl_file_attribution_stream: the lines a pushed commit adds (stdin, read once as a stream),
# checked for attribution by SHAPE, so a file may state the no-attribution policy, credit a
# person, or link to Claude Code's docs. 0, with the first offending line in GITCTL_HIT, when a
# line is one of:
#   - a trailer: optional leading space and one comment or quote marker (# // /* * ; -- % <!-- >),
#     then Co-Authored-By: or Signed-off-by: naming an AI tool (GITCTL_AI_FILE_ID as whole words
#     in the name or email, or an email at GITCTL_AI_VENDOR_MAIL);
#   - a "Generated with" footer, the whole line: the same optional lead, an optional robot
#     emoji, generated/created/written/authored/made/produced with/by/using/via/in, then the
#     tool's name (an AI word with up to one word before and three after, optionally a markdown
#     link) and nothing more but a full stop or a comment closer ("Generated with [Claude
#     Code](...)", "Generated with Claude Code", "<!-- Generated by GitHub Copilot -->"). A
#     sentence that goes on ("Written by Claude Code on the user's behalf (...") is prose.
# Prose that only mentions a trailer ("No `Co-Authored-By:` trailers naming Claude"), a bare
# robot emoji in text and a claude.ai/code link pass. Decided in build-plan-k8s-hardening.md,
# decision (03, P6, narrowed).
gitctl_file_attribution_stream() {
    local lead line low tail name email words trailer_re
    lead='^[[:space:]]*((#+|//+|/?\*+|;+|--|%+|<!--|>+)[[:space:]]*)?'
    trailer_re="${lead}(co[- ]?authored[- ]?by|signed[- ]?off[- ]?by)[[:space:]]*:(.*)$"
    GITCTL_HIT=""
    while IFS= read -r line; do
        line="${line%$'\r'}"
        low="${line,,}"
        if [[ "$low" =~ $trailer_re ]]; then
            tail="${BASH_REMATCH[4]}"
            name="${tail%%<*}" email=""
            if [[ "$tail" == *"<"*">"* ]]; then email="${tail#*<}"; email="${email%%>*}"; fi
            if [ -n "$email" ] && printf '%s\n' "${email#*@}" | LC_ALL=C grep -qiE "(^|\.)(${GITCTL_AI_VENDOR_MAIL})\$"; then
                GITCTL_HIT="$line"; return 0
            fi
            words=$(printf '%s %s\n' "$name" "$email" | LC_ALL=C tr -c 'A-Za-z0-9\n' ' ')
            if printf '%s\n' "$words" | LC_ALL=C grep -qiE "(^|[^a-z0-9])(${GITCTL_AI_FILE_ID})([^a-z0-9]|\$)"; then
                GITCTL_HIT="$line"; return 0
            fi
            continue
        fi
        # Not a trailer: then a candidate line is a footer.
        GITCTL_HIT="$line"; return 0
    done < <(LC_ALL=C grep -iE \
        -e "${lead}(co[- ]?authored[- ]?by|signed[- ]?off[- ]?by)[[:space:]]*:" \
        -e "${lead}($(printf '\360\237\244\226')[[:space:]]*)?(generated|created|written|authored|made|produced)[[:space:]]+(with|by|using|via|in)[[:space:]]+\[?([A-Za-z0-9.-]+[[:space:]]+)?(${GITCTL_AI_FILE_ID})([[:space:]]+[A-Za-z0-9.-]+){0,3}\]?(\([^)]*\))?[[:space:]]*[.!]?[[:space:]]*(-->|\*/)?[[:space:]]*\$")
    GITCTL_HIT=""
    return 1
}

gitctl_check_text() { # TEXT WHAT
    gitctl_attribution "$1" || return 0
    gitctl_refuse "$2 carries AI attribution (${GITCTL_HIT:0:120}); no attribution in commits, PRs or comments"
}

# Names that mark an author or committer as an AI tool, matched as whole words (case-insensitive)
# in the name and in the email's local part and domain. Narrower than GITCTL_AI: words that are
# also people's names (cody, aider, ...) are left out here, where a person's own name is checked.
GITCTL_AI_ID='claude|anthropic|openai|chatgpt|gpt[0-9]*|copilot|gemini|codex|cursor|devin|codeium|windsurf|tabnine|codewhisperer|deepseek|bot'
# The user's own identity (gitctl sets them from the GitHub login's identity file): a field equal
# to the user's own is never refused, so a user whose name is one of the words above (Devin) can
# still push their own commits.
GITCTL_OWN_NAME="" GITCTL_OWN_EMAIL=""

# gitctl_ai_identity LINES: 0 when any author or committer in LINES is an AI tool or a bot. Each
# line is "author|committer <name> <<email>> ..." (a commit's header) or "<name> <<email>>".
gitctl_ai_identity() {
    local line name email words
    while IFS= read -r line; do
        line="${line#author }"; line="${line#committer }"
        case "$line" in *"<"*">"*) ;; *) [ -n "$line" ] || continue; name="$line" email="" ;; esac
        if [[ "$line" == *"<"*">"* ]]; then
            name="${line%%<*}"; email="${line#*<}"; email="${email%%>*}"
        fi
        name="${name%"${name##*[![:space:]]}"}"
        words=""
        if [ -z "$GITCTL_OWN_NAME" ] || [ "${name,,}" != "${GITCTL_OWN_NAME,,}" ]; then words+=" ${name}"; fi
        if [ -z "$GITCTL_OWN_EMAIL" ] || [ "${email,,}" != "${GITCTL_OWN_EMAIL,,}" ]; then words+=" ${email}"; fi
        # Words: runs of letters and digits (claude-bot is claude and bot; '[bot]' is bot).
        if printf '%s\n' "$words" | LC_ALL=C tr -c 'A-Za-z0-9\n' ' ' \
                | LC_ALL=C grep -qiE "(^|[^a-z0-9])(${GITCTL_AI_ID})([^a-z0-9]|$)"; then
            return 0
        fi
    done <<<"$1"
    return 1
}

# gitctl_slug_from_url URL: owner/name (in GITCTL_SLUG) of https://github.com/<owner>/<name>[.git].
# Nothing else: not http (the token would cross in the clear), not ssh, not another host, not a
# transport helper.
gitctl_slug_from_url() {
    local re='^https://github\.com/([A-Za-z0-9][A-Za-z0-9-]*)/([A-Za-z0-9._-]+)$' name
    [[ "$1" =~ $re ]] || { gitctl_refuse "origin ${1} is not https://github.com/<owner>/<name>"; return 1; }
    name="${BASH_REMATCH[2]%.git}"
    case "$name" in ""|.|..) gitctl_refuse "origin ${1} names no repo"; return 1 ;; esac
    GITCTL_SLUG="${BASH_REMATCH[1]}/${name}"
}

gitctl_slug_ok() {
    if [[ "$1" =~ ^[A-Za-z0-9][A-Za-z0-9-]*/[A-Za-z0-9._-]+$ ]] && [ "${1#*/}" != . ] && [ "${1#*/}" != .. ]; then
        return 0
    fi
    gitctl_refuse "${1}: not an owner/name"
}

gitctl_number_ok() {
    [[ "$1" =~ ^[1-9][0-9]{0,9}$ ]] || { gitctl_refuse "${1}: not a pull request number"; return 1; }
}

# gitctl_branch_ok GIT NAME: a branch name git accepts, that cannot be read as an option.
# Asked of git from /, with no config, so neither the caller's folder nor any config file
# has a say.
gitctl_branch_ok() {
    case "$2" in
        ""|-*|*:*|+*) gitctl_refuse "${2}: not a branch name"; return 1 ;;
    esac
    if ! (cd / && env -i PATH=/usr/bin:/bin GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null \
            "$1" check-ref-format --branch "$2" >/dev/null 2>&1); then
        gitctl_refuse "${2}: not a branch name"; return 1
    fi
}

# --- the issue-scoped GitHub API passthrough (GIT-07) ----------------------------------------
#
# GitHub issues go through the git container: `gitctl api` (as gitcred) passes a request to
# GitHub's REST API only when its method and path are one of the rows below, on a repo the user
# added, with a body of the row's keys only and no AI attribution. These are the calls prawduct's
# backlog makes (`gh api`, lib/backlog/transport.py) and the `gh issue` forms of the sessions' gh
# stand-in. No issue delete, transfer or lock: there is no row for them.
#
# One row an endpoint: METHOD PATH KIND QUERY BODY. PATH is under repos/<owner>/<name>/, except
# /user (who the login is). {n} is an issue number, {label} a URL-encoded label name, {id} an
# issue's id or node id, {branch} a branch name (it may hold slashes). KIND is read or write: a
# write runs only for the request holder (gitctl.sh, WRITE_VERBS). QUERY lists the query keys a
# GET may carry; BODY the JSON body's keys (- for none).
GITCTL_API_TABLE='
GET    /user                                read   -                                                        -
GET    issues                               read   state,labels,assignee,since,sort,direction,per_page,page -
GET    issues/{n}                           read   -                                                        -
GET    issues/{n}/comments                  read   per_page,page                                            -
GET    issues/{n}/sub_issues                read   per_page,page                                            -
GET    issues/{n}/timeline                  read   per_page,page                                            -
GET    issues/{n}/dependencies/blocked_by   read   per_page,page                                            -
GET    labels                               read   per_page,page                                            -
GET    branches/{branch}                    read   -                                                        -
POST   issues                               write  -   title,body,labels,assignees,milestone
PATCH  issues/{n}                           write  -   title,body,state,state_reason,labels,assignees,milestone
POST   issues/{n}/labels                    write  -   labels
DELETE issues/{n}/labels/{label}            write  -   -
POST   issues/{n}/comments                  write  -   body
POST   labels                               write  -   name,color,description
POST   issues/{n}/sub_issues                write  -   sub_issue_id
DELETE issues/{n}/sub_issue                 write  -   sub_issue_id
POST   issues/{n}/dependencies/blocked_by   write  -   issue_id
DELETE issues/{n}/dependencies/blocked_by/{id} write -  -
'
GITCTL_API_MAX_BODY=65536

# gitctl_api_check GIT METHOD PATH: 0 when the call is a row of the table, with
# GITCTL_API_SLUG (owner/name; empty for /user), GITCTL_API_KIND (read or write), GITCTL_API_BODY
# (the row's body keys, or -) and GITCTL_API_PATH (the path as GitHub is given it: no leading /).
gitctl_api_check() {
    local git="$1" method="$2" path="${3#/}" query="" rest="" m pat kind qkeys bkeys re seg q k v seen=","
    local n_re='[1-9][0-9]{0,9}' label_re='[A-Za-z0-9._~%:-]{1,300}' id_re='[A-Za-z0-9_-]{1,100}'
    GITCTL_API_SLUG="" GITCTL_API_KIND="" GITCTL_API_BODY="" GITCTL_API_PATH=""
    case "$method" in GET|POST|PATCH|DELETE) ;; *) gitctl_refuse "${method}: not GET, POST, PATCH or DELETE"; return 1 ;; esac
    case "$path" in *\?*) query="${path#*\?}"; path="${path%%\?*}" ;; esac
    # Plain path characters only; no empty, . or .. part, and no encoded dot, so nothing GitHub
    # decodes can climb out of the row's place.
    [[ "$path" =~ ^[A-Za-z0-9._~%:/-]+$ ]] || { gitctl_refuse "${path:0:80}: not a GitHub API path"; return 1; }
    case "/${path}/" in *//*|*/./*|*/../*|*%2[eE]*|*..*) gitctl_refuse "${path:0:80}: not a GitHub API path"; return 1 ;; esac
    if [ "$path" = user ]; then rest=/user
    else
        [[ "$path" =~ ^repos/([^/]+)/([^/]+)/(.+)$ ]] || { gitctl_refuse "${path:0:80}: not under repos/<owner>/<name>/"; return 1; }
        GITCTL_API_SLUG="${BASH_REMATCH[1]}/${BASH_REMATCH[2]}" rest="${BASH_REMATCH[3]}"
        gitctl_slug_ok "$GITCTL_API_SLUG" || { GITCTL_API_SLUG=""; return 1; }
    fi
    while read -r m pat kind qkeys bkeys; do
        [ -n "$m" ] && [ "$m" = "$method" ] || continue
        re="${pat//'{n}'/$n_re}"
        re="${re//'{label}'/$label_re}"
        re="${re//'{id}'/$id_re}"
        re="${re//'{branch}'/(.+)}"
        [[ "$rest" =~ ^${re}$ ]] || continue
        if [[ "$pat" == *"{branch}"* ]]; then gitctl_branch_ok "$git" "${BASH_REMATCH[1]}" || return 1; fi
        if [ -n "$query" ]; then
            [ "$method" = GET ] && [ "$qkeys" != - ] || { gitctl_refuse "${method} ${pat} takes no query"; return 1; }
            IFS='&' read -ra q <<<"$query"
            for seg in "${q[@]}"; do
                k="${seg%%=*}" v="${seg#*=}"
                [ "$seg" != "$k" ] || { gitctl_refuse "${seg:0:40}: a query part with no value"; return 1; }
                case ",${qkeys}," in *",${k},"*) ;; *) gitctl_refuse "${k:0:40}: not a query key ${pat} takes"; return 1 ;; esac
                case "$seen" in *",${k},"*) gitctl_refuse "${k}: given twice"; return 1 ;; esac
                seen+="${k},"
                [[ "$v" =~ ^[A-Za-z0-9._~%+:,*-]{0,200}$ ]] || { gitctl_refuse "${k}: not a plain value"; return 1; }
                case "$k" in per_page|page) [[ "$v" =~ ^[1-9][0-9]{0,3}$ ]] || { gitctl_refuse "${k}: not a page number"; return 1; } ;; esac
            done
        fi
        GITCTL_API_KIND="$kind" GITCTL_API_BODY="$bkeys" GITCTL_API_PATH="${path}${query:+?$query}"
        return 0
    done <<<"$GITCTL_API_TABLE"
    gitctl_refuse "${method} ${path:0:80}: not an issue call the git container passes on (gitctl api --help)"
}

# gitctl_api_body KEYS TEXT: the body of a write, checked against the row's KEYS (- for none):
# a JSON object of those keys only, each of its type, with no AI attribution and no control
# characters but in a body. Prints it again (compact, only those keys), or 1 with the reason.
gitctl_api_body() {
    local keys="$1" text="$2" json words
    if [ "$keys" = - ]; then
        [ -z "${text//[[:space:]]/}" ] || { gitctl_refuse "this call takes no body"; return 1; }
        return 0
    fi
    [ "${#text}" -le "$GITCTL_API_MAX_BODY" ] || { gitctl_refuse "the body is longer than ${GITCTL_API_MAX_BODY} bytes"; return 1; }
    json=$(printf '%s' "$text" | jq -c --arg keys "$keys" '
        def str: type == "string";
        def strs: type == "array" and length <= 100 and all(.[]; type == "string" and length <= 300);
        ($keys | split(",")) as $k
        | if type != "object" then error("not an object")
          elif (keys - $k | length) > 0 then error("a key this call does not take: \(keys - $k | join(","))")
          else . end
        | if has("title") and ((.title | str) | not) then error("title: not text") else . end
        | if has("body") and ((.body | str) | not) then error("body: not text") else . end
        | if has("name") and ((.name | str) | not) then error("name: not text") else . end
        | if has("description") and ((.description | str) | not) then error("description: not text") else . end
        | if has("color") and ((.color | str and test("^[0-9a-fA-F]{6}$")) | not) then error("color: not a colour") else . end
        | if has("state") and (.state != "open" and .state != "closed") then error("state: not open or closed") else . end
        | if has("state_reason") and ((.state_reason == null or .state_reason == "completed" or .state_reason == "not_planned" or .state_reason == "reopened") | not) then error("state_reason: not completed, not_planned or reopened") else . end
        | if has("labels") and ((.labels | strs) | not) then error("labels: not a list of names") else . end
        | if has("assignees") and ((.assignees | strs) | not) then error("assignees: not a list of logins") else . end
        | if has("milestone") and ((.milestone == null or (.milestone | type) == "number") | not) then error("milestone: not a number") else . end
        | if has("sub_issue_id") and (((.sub_issue_id | type) == "number" or (.sub_issue_id | str)) | not) then error("sub_issue_id: not an id") else . end
        | if has("issue_id") and (((.issue_id | type) == "number" or (.issue_id | str)) | not) then error("issue_id: not an id") else . end
        | with_entries(select(.key as $x | $k | index($x)))' 2>&1) \
        || { gitctl_refuse "the body: $(printf '%s' "$json" | sed -n 's/^jq: error ([^)]*): //p' | head -n1 | cut -c1-120)"; return 1; }
    # One-line texts: no control characters at all.
    if printf '%s' "$json" | jq -e '[.title, .name, .description, (.labels // [])[], (.assignees // [])[]]
            | map(select(. != null) | explode[]) | any(. < 32 or . == 127)' >/dev/null; then
        gitctl_refuse "a title, name or label carries control characters"; return 1
    fi
    if printf '%s' "$json" | jq -e '(.body // "") | explode | any((. < 32 and . != 9 and . != 10 and . != 13) or . == 127)' >/dev/null; then
        gitctl_refuse "the body carries control characters"; return 1
    fi
    words=$(printf '%s' "$json" | jq -r '[.title, .body, .name, .description, (.labels // [])[]] | map(select(. != null)) | .[]')
    gitctl_check_text "$words" "the issue text" || return 1
    printf '%s' "$json"
}

# gitctl_api_etag ETAG: an ETag as GitHub gives one (a quoted token, maybe weak).
gitctl_api_etag() {
    [[ "$1" =~ ^(W/)?\"[A-Za-z0-9_-]{1,128}\"$ ]] || { gitctl_refuse "${1:0:40}: not an ETag"; return 1; }
}

# gitctl_agent_git GIT ARGS...: the agent's own git, in a working copy anyone in the session
# group may have written (gitctl's `ag`, and the request watcher's reads). It runs as the agent,
# never as gitrun, so the copy's config cannot reach the login; still, the settings that run a
# program on the steps gitctl takes (hooks, fsmonitor, auto gc) are pinned off, and no
# transport is allowed: bundles are imported with `bundle unbundle`, never fetched. A filter
# driver the copy's config names runs its clean or smudge command on files git reads or writes
# (status, worktree remove, reset), so every driver named there is overridden for the call
# (clean and smudge `cat`, no process). The names are read from the config just before the
# call, through GIT_CONFIG_COUNT, which takes a driver name of any spelling where `-c` would
# split it at an `=`. Residual: a driver a session adds between that read and the call.
# The system config is kept (no GIT_CONFIG_NOSYSTEM): its safe.directory is what lets the agent
# read a working copy the session user owns.
gitctl_agent_git() {
    local git="$1" dir=. key d n=0 envs=()
    local -A seen=()
    shift
    [ "${1:-}" = -C ] && dir="$2"
    while IFS= read -r key; do
        d="${key#filter.}"; d="${d%.*}"
        { [ -n "$d" ] && [ -z "${seen[$d]:-}" ]; } || continue
        seen[$d]=1
        envs+=("GIT_CONFIG_KEY_${n}=filter.${d}.clean" "GIT_CONFIG_VALUE_${n}=cat"); n=$((n + 1))
        envs+=("GIT_CONFIG_KEY_${n}=filter.${d}.smudge" "GIT_CONFIG_VALUE_${n}=cat"); n=$((n + 1))
        envs+=("GIT_CONFIG_KEY_${n}=filter.${d}.process" "GIT_CONFIG_VALUE_${n}="); n=$((n + 1))
    done < <(env -i HOME="${HOME:-/}" PATH=/usr/bin:/bin GIT_CONFIG_GLOBAL=/dev/null \
        "$git" -C "$dir" config --name-only --get-regexp '^filter\..*\.(clean|smudge|process)$' 2>/dev/null)
    env -i HOME="${HOME:-/}" PATH=/usr/bin:/bin LANG=C.UTF-8 GIT_CONFIG_GLOBAL=/dev/null \
        GIT_TERMINAL_PROMPT=0 GIT_NO_REPLACE_OBJECTS=1 GIT_CONFIG_COUNT="$n" ${envs[@]+"${envs[@]}"} \
        "$git" -c core.hooksPath=/dev/null -c core.fsmonitor=false -c gc.auto=0 \
        -c maintenance.auto=false -c protocol.allow=never -c credential.helper= "$@"
}

# --- the PreToolUse hook: a courtesy, not the enforcement ----------------------------------

# gitctl_hook_command STRING: a Bash command Claude is about to run.
gitctl_hook_command() {
    local s="$1"
    GITCTL_REASON=""
    if printf '%s' "$s" | grep -qE '(^|[^[:alnum:]_./-])(sudo|su|doas|runuser|setpriv|pkexec)([^[:alnum:]_-]|$)'; then
        gitctl_refuse "switching user is refused; gitctl switches for its own verbs"; return 1
    fi
    if printf '%s' "$s" | grep -qE '/var/lib/gitctl|/etc/sudoers'; then
        gitctl_refuse "the command touches the GitHub login's home or the sudo rules"; return 1
    fi
    if printf '%s' "$s" | grep -qE '/etc/claude-code|/opt/aidc|/etc/gitconfig' \
        && printf '%s' "$s" | grep -qE '>|(^|[^[:alnum:]_-])(tee|cp|mv|rm|ln|chmod|chown|install|truncate|dd|sed[[:space:]]+-i|perl|python3?)([^[:alnum:]_-]|$)'; then
        gitctl_refuse "the command changes the git container's protected files"; return 1
    fi
    if printf '%s' "$s" | grep -qE '(^|[^[:alnum:]_-])gh([^[:alnum:]_-]|$).*auth.*login'; then
        gitctl_refuse "gh auth login here would keep the login where the agent can read it; the user runs: gitctl login"; return 1
    fi
    if printf '%s' "$s" | grep -qE '(^|[^[:alnum:]_-])(git|gitctl)([^[:alnum:]_-]|$)' && gitctl_attribution "$s"; then
        gitctl_refuse "the command carries AI attribution (${GITCTL_HIT:0:120}); no attribution in commits, PRs or comments"; return 1
    fi
    return 0
}

# gitctl_hook_path PATH: an Edit or Write target.
gitctl_hook_path() {
    local r
    r=$(realpath -m -- "$1" 2>/dev/null || printf '%s' "$1")
    case "$r" in
        /opt/aidc/*|/etc/claude-code/*|/etc/sudoers*|/etc/gitconfig|/var/lib/gitctl/*)
            gitctl_refuse "${1} is one of the git container's protected files"; return 1 ;;
    esac
    return 0
}
